export const WORDS = { en: EN };

/** A key's words with its slots filled. A slot's value may be a function of the language the words were found in (a date
 *  says its month in that language). A slot not given stays as written, so a missing one shows rather than vanishes. */
export function fill(w, s, L) {
  return String(w == null ? "" : w).replace(/[{]([A-Za-z0-9]+)[}]/g, function (m, k) {
    var v = s ? s[k] : undefined;
    if (typeof v === "function") v = v(L);
    return v == null ? m : String(v);
  });
}
/** The same, as markup: the words escaped, **x** bold, and each slot's value put in as markup, which the caller escapes. */
export function fillHtml(w, s, L) {
  var e = String(w == null ? "" : w).replace(/[&<>"]/g, function (c) { return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]; });
  return fill(e.replace(/[*][*]([^*]+)[*][*]/g, function (m, b) { return "<b>" + b + "</b>"; }), s, L);
}
/** A size in words, from a language's two forms: {n} {u} at one and under, and above one; a unit already plural is kept. */
export function unitsIn(one, many, q, u) {
  u = u || "unit";
  return +q > 1 && u.slice(-1) === "s" ? q + " " + u : fill(+q > 1 ? many : one, { n: q, u: u });
}

/** A refusal a customer can meet: its English and its code, and its slots where it has any, for the page to word. */
export function refusal(code, vars) {
  const w = EN["e." + code];
  if (w == null) throw new Error("no English for the refusal " + code);
  return vars ? { error: fill(w, vars, "en"), code, vars } : { error: w, code };
}
