#!/usr/bin/env node
/* tools/paycrcsync.mjs: SALT QR'S PAYLOAD RULE, CARRIED INTO THE STATEMENTS SITE.
 *
 * The Counter reads each account's DuitNow payload from Salt QR (stmt/paycodes.js) and refuses one whose checksum fails. Salt QR's own
 * rule is ONE copy (its tools/store.js `crc16` and `payloadError`, never reimplemented), and a Worker under stmt/ may import only a
 * sibling, so those two functions are written into stmt/paycrc.js as text, the way tools/qrsync.mjs carries engine/qr.mjs. Nothing
 * private is in them: they are arithmetic. A change to the rule is made in qr-command, then synced here.
 *
 *   node tools/paycrcsync.mjs --sync    write stmt/paycrc.js from qr-command's tools/store.js
 *   node tools/paycrcsync.mjs --check   non-zero if they differ; stands down (exit 0, says so) where qr-command is not on the machine (CI)
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const QR_REPO = process.env.QR_REPO || "C:/Users/maakm/Claude/Code/qr-command";
export const SOURCE = join(QR_REPO, "tools", "store.js");
export const TARGET = join(REPO, "stmt", "paycrc.js");

const BANNER =
  "/* GENERATED FROM qr-command/tools/store.js BY tools/paycrcsync.mjs --sync. DO NOT EDIT THIS FILE.\n"
  + " * Salt QR's one payload rule (`crc16`, `payloadError`), carried verbatim because a Worker under stmt/ may import only a sibling.\n"
  + " * Change it in qr-command, run the sync, commit both; the gate runs --check where qr-command is present. */\n";

/** The two functions as text, from `export function crc16` to the close of `payloadError`; throws if the source no longer holds them. */
export function extract(src) {
  const a = src.indexOf("export function crc16(");
  const b = src.indexOf("export function payloadError(");
  const end = b < 0 ? -1 : src.indexOf("\n}\n", b);
  if (a < 0 || b < a || end < 0) throw new Error("qr-command's tools/store.js no longer holds crc16 and payloadError in that order");
  return src.slice(a, end + 3);
}

export const sourcePresent = () => existsSync(SOURCE);
/** What stmt/paycrc.js should hold now. */
export function expected() { return BANNER + extract(readFileSync(SOURCE, "utf8").replace(/\r\n/g, "\n")); }
export function matches() {
  let got = ""; try { got = readFileSync(TARGET, "utf8"); } catch (e) { return false; }
  return got === expected();
}

function main() {
  const check = process.argv.includes("--check");
  if (!check && !process.argv.includes("--sync")) { console.error("usage: node tools/paycrcsync.mjs --sync | --check"); process.exit(2); }
  if (!sourcePresent()) { console.log("paycrcsync: qr-command is not on this machine; " + (check ? "nothing to check against" : "nothing written")); return; }
  if (check) {
    if (matches()) { console.log("stmt/paycrc.js is qr-command's crc16 and payloadError, byte for byte"); return; }
    console.error("::error::stmt/paycrc.js has drifted from qr-command's tools/store.js. Run: node tools/paycrcsync.mjs --sync");
    process.exit(1);
  }
  const t = expected();
  writeFileSync(TARGET, t);
  console.log("wrote stmt/paycrc.js from qr-command (" + t.length + " bytes)");
}

if (import.meta.url === pathToFileURL(process.argv[1] || "").href) main();
