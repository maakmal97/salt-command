#!/usr/bin/env node
/* tools/geosite.mjs: THE DISTANCE, CARRIED INTO THE STATEMENTS SITE (20 Oct 2026).
 *
 * Salt Admin says a delivery's distance under Delivery cost, measured as the Desk measures it for the fee. The statements Worker may
 * import only a sibling (nothing under stmt/ imports from src/, tools/ or a node builtin) and rule 1 forbids a second copy of anything
 * the Desk computes, so this writes stmt/geo.js as engine/geo.mjs VERBATIM under a generated banner, as tools/qrsync.mjs does for the
 * QR encoder, and --check fails if they have drifted. One function, one place to edit it.
 *
 *   node tools/geosite.mjs --sync     write stmt/geo.js from engine/geo.mjs
 *   node tools/geosite.mjs --check    non-zero if they differ (the gate runs it)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const SOURCE = join(REPO, "engine", "geo.mjs");
export const TARGET = join(REPO, "stmt", "geo.js");

const BANNER =
  "/* GENERATED FROM engine/geo.mjs BY tools/geosite.mjs --sync. DO NOT EDIT THIS FILE.\n"
  + " * The statements Worker may import only a sibling, so the one distance is carried here verbatim rather than imported or\n"
  + " * rewritten. Edit engine/geo.mjs, run the sync, and commit both; the gate runs --check. Everything below is that file. */\n";

/** What stmt/geo.js should contain, given what engine/geo.mjs contains now. */
export function expected() { return BANNER + readFileSync(SOURCE, "utf8"); }

/** True when the shipped copy is what the source produces. */
export function matches() {
  let got = "";
  try { got = readFileSync(TARGET, "utf8"); } catch (e) { return false; }
  return got === expected();
}

const check = process.argv.includes("--check");
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (!check && !process.argv.includes("--sync")) { console.error("usage: node tools/geosite.mjs --sync | --check"); process.exit(2); }
  if (check) {
    if (matches()) console.log("stmt/geo.js is engine/geo.mjs, byte for byte");
    else { console.error("::error::stmt/geo.js has drifted from engine/geo.mjs. Run: node tools/geosite.mjs --sync"); process.exit(1); }
  } else { writeFileSync(TARGET, expected()); console.log("wrote stmt/geo.js from engine/geo.mjs"); }
}
